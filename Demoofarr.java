class Demoofarr {

    // Static method with parameters and return type
    static int add(int a, int b) {
        int sum = a + b;
        return sum;
    }

    public static void main(String[] args) {

        // Calling the method
        int result = add(10, 20);

        // Display result
        System.out.println("Sum = " + result);
    }
}
